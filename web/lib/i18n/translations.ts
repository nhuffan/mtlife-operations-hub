export function getTranslations(locale: Locale) {
  if (locale === "vi") return VI_TRANSLATIONS;
  if (locale === "zh-CN") return ZH_TRANSLATIONS;
  return {};
}

const ENGLISH_SOURCE_BY_TRANSLATION = new Map(
  [VI_TRANSLATIONS, ZH_TRANSLATIONS].flatMap((dictionary) =>
    Object.entries(dictionary).map(([english, translated]) => [translated, english] as const)
  )
);

export function getLegacySourceText(text: string) {
  const exact = ENGLISH_SOURCE_BY_TRANSLATION.get(text);
  if (exact) return exact;

  const reversePatterns: Array<[RegExp, (...parts: string[]) => string]> = [
    [/^Tất cả \((\d+) hóa đơn\)$/, (count) => `All (${count} invoices)`],
    [/^Tất cả \((\d+) giao dịch\)$/, (count) => `All (${count} transactions)`],
    [/^Tháng (\d{2}\/\d{4})(?: \((\d+) hóa đơn\))?$/, (month, count) => `Month ${month}${count ? ` (${count} invoices)` : ""}`],
    [/^Tháng (\d{2}\/\d{4})(?: \((\d+) giao dịch\))?$/, (month, count) => `Month ${month}${count ? ` (${count} transactions)` : ""}`],
    [/^\(Tháng (\d{2}\/\d{4})\)$/, (month) => `(Month ${month})`],
    [/^全部（(\d+) 张发票）$/, (count) => `All (${count} invoices)`],
    [/^全部（(\d+) 笔转账）$/, (count) => `All (${count} transactions)`],
    [/^(\d{4})年(\d{1,2})月(?:（(\d+) 张发票）)?$/, (year, month, count) => `Month ${month.padStart(2, "0")}/${year}${count ? ` (${count} invoices)` : ""}`],
    [/^(\d{4})年(\d{1,2})月(?:（(\d+) 笔转账）)?$/, (year, month, count) => `Month ${month.padStart(2, "0")}/${year}${count ? ` (${count} transactions)` : ""}`],
    [/^（(\d{4})年(\d{1,2})月）$/, (year, month) => `(Month ${month.padStart(2, "0")}/${year})`],
  ];

  for (const [pattern, format] of reversePatterns) {
    const match = text.match(pattern);
    if (match) return format(...match.slice(1));
  }
  return text;
}

